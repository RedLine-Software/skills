#!/usr/bin/env node
/**
 * fetch-fonts.mjs — the two faces BlockFrame needs that HyperFrames does not bundle.
 *
 * Inter ships with the framework; Noto Sans Thai (Thai glyphs) and Space Grotesk (label chrome)
 * do not. Pull their subsets from the Google Fonts CSS API with a browser user-agent, save every
 * woff2 locally, and rewrite the returned @font-face rules to local paths.
 *
 * Run once per project, from the project root:
 *
 *   node scripts/fetch-fonts.mjs --out assets/fonts
 *   node scripts/fetch-fonts.mjs --only notosansthai
 *
 * Re-run when the Thai character set changes. These are full subsets rather than text-subsetted,
 * so new words do not require a refetch — only new characters do.
 *
 * Requires network at build time only; the film itself resolves every font locally.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

const FAMILIES = [
  {
    slug: "notosansthai",
    query: "family=Noto+Sans+Thai:wght@400;500;600;700;900",
    note: "Thai glyphs — display, body and label fallback",
  },
  {
    slug: "spacegrotesk",
    query: "family=Space+Grotesk:wght@500;600;700",
    note: "label-pill chrome only",
  },
];

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 " +
  "(KHTML, like Gecko) Chrome/124.0 Safari/537.36";

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const outDir = path.resolve(process.cwd(), arg("out", "assets/fonts"));
const only = arg("only", null);
await mkdir(outDir, { recursive: true });

const picked = only ? FAMILIES.filter((f) => f.slug === only) : FAMILIES;
if (!picked.length) {
  console.error(`unknown --only "${only}"; known: ${FAMILIES.map((f) => f.slug).join(", ")}`);
  process.exit(1);
}

const chunks = [
  "/* Generated by scripts/fetch-fonts.mjs — Inter is bundled; these two are not. */",
];

for (const fam of picked) {
  const cssUrl = `https://fonts.googleapis.com/css2?${fam.query}&display=block`;
  const cssRes = await fetch(cssUrl, { headers: { "User-Agent": UA } });
  if (!cssRes.ok) throw new Error(`${fam.slug}: CSS HTTP ${cssRes.status}`);
  const css = await cssRes.text();

  const urls = [...new Set([...css.matchAll(/url\((https:\/\/[^)]+\.woff2)\)/g)].map((m) => m[1]))];
  if (!urls.length) throw new Error(`${fam.slug}: no woff2 urls in the returned css`);

  let out = css;
  for (const url of urls) {
    const name = `${fam.slug}-${createHash("sha1").update(url).digest("hex").slice(0, 10)}.woff2`;
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`${fam.slug}: woff2 HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    await writeFile(path.join(outDir, name), buf);
    out = out.split(url).join(name);
    console.log(`  ${fam.slug} ${name} ${buf.length} B  (${url.split("/").pop()})`);
  }
  chunks.push(`/* ${cssUrl} — ${fam.note} */`, out.trim());
}

const dest = path.join(outDir, "fonts.css");
await writeFile(dest, chunks.join("\n") + "\n");
console.log(`wrote ${path.relative(process.cwd(), dest)}`);
console.log(`link it from the root <head>: <link rel="stylesheet" href="${path.relative(process.cwd(), dest).split(path.sep).join("/")}">`);
